"""
RAMP Validation Engine

Overlays RAMP simulated stochastic profiles against real datalogger telemetry.
Calculates Tier 1 (Error) and Tier 2 (Structural) validation metrics.
Automatically detects the simulated file generated by Script 3.
"""
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import argparse
from pathlib import Path
import sys
import random

# Define paths matching the project structure
SCRIPT_DIR = Path(__file__).parent
PROJECT_ROOT = SCRIPT_DIR.parent.parent
INPUT_DIR_REAL = PROJECT_ROOT / "data" / "clean" / "timeseries"
INPUT_DIR_SIM = SCRIPT_DIR / "output"
OUTPUT_DIR = SCRIPT_DIR / "output"
FIGURES_DIR = OUTPUT_DIR / "figures"
METRICS_DIR = OUTPUT_DIR / "metrics"

# Ensure output directories exist
FIGURES_DIR.mkdir(parents=True, exist_ok=True)
METRICS_DIR.mkdir(parents=True, exist_ok=True)

def load_and_prep_data(user_id, num_days=None, target_months=None):
    """Loads real data and automatically locates the simulated data for the user."""
    print(f"\n[*] Loading Real Data for User: {user_id}")
    
    # 1. Load Real Data
    real_file = INPUT_DIR_REAL / f"tpdin_user_{user_id}.csv"
    if not real_file.exists():
        real_file = INPUT_DIR_REAL / f"old_user_{user_id}.csv"
        if not real_file.exists():
            print(f"[-] Error: Real data file not found for User {user_id} in {INPUT_DIR_REAL}")
            sys.exit(1)
            
    df_real = pd.read_csv(real_file)
    df_real['timestamp'] = pd.to_datetime(df_real['corrected_timestamp'], errors='coerce')
    df_real = df_real.dropna(subset=['timestamp'])
    
    # Calculate total real power safely
    zero_series = pd.Series(0.0, index=df_real.index)
    v_usb = df_real.get('v_usb', zero_series)
    c_usb = df_real.get('c_usb', zero_series)
    v_led_1 = df_real.get('v_led_1', zero_series)
    c_led_1 = df_real.get('c_led_1', df_real.get('c_led', zero_series)) # Handles OLD format
    v_led_2 = df_real.get('v_led_2', zero_series)
    c_led_2 = df_real.get('c_led_2', zero_series)
    
    p_led_1 = (v_led_1 * c_led_1).clip(lower=0)
    p_led_2 = (v_led_2 * c_led_2).clip(lower=0)
    p_usb = (v_usb * c_usb).clip(lower=0)
    
    df_real['p_total'] = p_led_1 + p_led_2 + p_usb
    df_real['date_only'] = df_real['timestamp'].dt.date
    df_real['time_decimal'] = df_real['timestamp'].dt.hour + df_real['timestamp'].dt.minute / 60.0

    # 2. Auto-Detect Simulated Data
    sim_pattern = f"simulated_profile_user_{user_id}_*.csv"
    sim_files = list(INPUT_DIR_SIM.glob(sim_pattern))
    
    if not sim_files:
        print(f"[-] Error: Simulated data not found for User {user_id}")
        print(f"    Looked for: {INPUT_DIR_SIM}/{sim_pattern}")
        print("    Ensure you run '3_run_ramp_simulation.py' first.")
        sys.exit(1)
        
    # Get the most recently modified file and extract the profile name
    sim_files.sort(key=lambda x: x.stat().st_mtime, reverse=True)
    sim_file = sim_files[0]
    profile_name = sim_file.stem.replace(f"simulated_profile_user_{user_id}_", "").upper()
    
    print(f"[*] Found Simulated Data: {sim_file.name}")
    print(f"[*] Profile Detected: {profile_name}")
    
    df_sim = pd.read_csv(sim_file)
    df_sim['timestamp'] = pd.to_datetime(df_sim['DateTime'])
    df_sim['p_total'] = df_sim['Total Load [W]']
    df_sim['date_only'] = df_sim['timestamp'].dt.date
    df_sim['time_decimal'] = df_sim['timestamp'].dt.hour + df_sim['timestamp'].dt.minute / 60.0

    # 3. Apply Time Filters (Months or N Days)
    if target_months is not None:
        print(f"[*] Limiting validation strictly to Months: {target_months}...")
        df_real = df_real[df_real['timestamp'].dt.month.isin(target_months)]
        df_sim = df_sim[df_sim['timestamp'].dt.month.isin(target_months)]
        if df_real.empty or df_sim.empty:
            print(f"[-] Warning: Missing data for selected months.")
            
    elif num_days is not None and num_days > 0:
        print(f"[*] Limiting validation to first {num_days} days...")
        real_days = sorted(df_real['date_only'].unique())[:num_days]
        sim_days = sorted(df_sim['date_only'].unique())[:num_days]
        df_real = df_real[df_real['date_only'].isin(real_days)]
        df_sim = df_sim[df_sim['date_only'].isin(sim_days)]
        
    print(f"[+] Real data active: {df_real['date_only'].nunique()} days")
    print(f"[+] Sim data active:  {df_sim['date_only'].nunique()} days")

    if df_real.empty or df_sim.empty:
        print("[-] Cannot proceed: Datasets are empty after filtering.")
        sys.exit(1)

    # 4. Create standardized time bins (15-minute intervals) for smooth averaging
    bins = np.arange(0, 24.25, 0.25)
    df_real['time_bin'] = pd.cut(df_real['time_decimal'], bins, labels=bins[:-1])
    df_sim['time_bin'] = pd.cut(df_sim['time_decimal'], bins, labels=bins[:-1])

    return df_real, df_sim, profile_name


def plot_shadows_and_average(df_real, df_sim, user_id, profile_name):
    """Plot 1: Side-by-side plot of all daily curves (soft) overlaid with the mean curve (strong)."""
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 6), sharey=True)
    
    # REAL DATA PLOT
    for date in df_real['date_only'].unique():
        day_data = df_real[df_real['date_only'] == date]
        ax1.plot(day_data['time_decimal'], day_data['p_total'], color='gray', alpha=0.08, linewidth=1)
        
    real_mean = df_real.groupby('time_bin', observed=True)['p_total'].mean()
    ax1.plot(real_mean.index.astype(float), real_mean.values, color='black', linewidth=3.5, label='Real Average Load')
    
    ax1.set_title(f'Real Measured Data (User {user_id})\nDaily Variance vs Average', fontsize=14, fontweight='bold')
    ax1.set_xlabel('Hour of the Day', fontsize=12)
    ax1.set_ylabel('Power Demand (W)', fontsize=12)
    ax1.set_xticks(np.arange(0, 25, 3))
    ax1.grid(True, linestyle='--', alpha=0.5)
    ax1.legend(loc='upper right', fontsize=11)
    ax1.set_ylim(bottom=0)

    # SIMULATED DATA PLOT
    for date in df_sim['date_only'].unique():
        day_data = df_sim[df_sim['date_only'] == date]
        ax2.plot(day_data['time_decimal'], day_data['p_total'], color='cornflowerblue', alpha=0.08, linewidth=1)
        
    sim_mean = df_sim.groupby('time_bin', observed=True)['p_total'].mean()
    ax2.plot(sim_mean.index.astype(float), sim_mean.values, color='darkblue', linewidth=3.5, label='Simulated Average Load')

    ax2.set_title(f'RAMP Simulation ({profile_name})\nDaily Variance vs Average', fontsize=14, fontweight='bold')
    ax2.set_xlabel('Hour of the Day', fontsize=12)
    ax2.set_xticks(np.arange(0, 25, 3))
    ax2.grid(True, linestyle='--', alpha=0.5)
    ax2.legend(loc='upper right', fontsize=11)

    plt.tight_layout()
    out_path = FIGURES_DIR / f"val_shadows_mean_U{user_id}_{profile_name.lower()}.png"
    plt.savefig(out_path, dpi=300)
    print(f"✓ Saved Shadow Plot: {out_path.name}")
    plt.close()


